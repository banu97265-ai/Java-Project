    private void addStudentFromForm() {

    try {

        // Read basic student information
        String registerNumber =
                txtRegisterNumber.getText().trim();

        String name =
                txtName.getText().trim();

        String department =
                txtDepartment.getText().trim();

        int year =
                Integer.parseInt(txtYear.getText().trim());

        double cgpa =
                Double.parseDouble(txtCgpa.getText().trim());

        int aptitudeRank =
                Integer.parseInt(txtAptitudeRank.getText().trim());

        // Create Student object
        Student student = new Student(
                registerNumber,
                name,
                department,
                year,
                cgpa,
                aptitudeRank
        );

        // Add programming platforms
        for (int i = 0; i < platformNameFields.size(); i++) {

            String platformName =
                    platformNameFields.get(i).getText().trim();

            int rank =
                    Integer.parseInt(
                            platformRankFields.get(i)
                                    .getText().trim()
                    );

            double score =
                    Double.parseDouble(
                            platformScoreFields.get(i)
                                    .getText().trim()
                    );

            int problemsSolved =
                    Integer.parseInt(
                            platformProblemsFields.get(i)
                                    .getText().trim()
                    );

            ProgrammingPlatform platform =
                    new ProgrammingPlatform(
                            platformName,
                            rank,
                            score,
                            problemsSolved
                    );

            student.getPlatforms().add(platform);
        }

        // Send student to backend
        studentService.addStudent(student);

        JOptionPane.showMessageDialog(
                this,
                "Student added successfully!",
                "Success",
                JOptionPane.INFORMATION_MESSAGE
        );

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Please enter valid numeric values.",
                "Invalid Input",
                JOptionPane.ERROR_MESSAGE
        );

    } catch (InvalidInputException e) {

        JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Invalid Input",
                JOptionPane.ERROR_MESSAGE
        );
    }
}
