private void generatePlatformFields() {

    // Clear old platform fields
    pnlPlatforms.removeAll();

    platformNameFields.clear();
    platformRankFields.clear();
    platformScoreFields.clear();
    platformProblemsFields.clear();

    // Get number of platforms
    int numberOfPlatforms;

    try {
        numberOfPlatforms =
                Integer.parseInt(txtPlatformCount.getText().trim());

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Please enter a valid number of platforms.",
                "Invalid Input",
                JOptionPane.ERROR_MESSAGE
        );

        return;
    }

    // Validate number of platforms
    if (numberOfPlatforms <= 0) {

        JOptionPane.showMessageDialog(
                this,
                "Number of platforms must be greater than 0.",
                "Invalid Input",
                JOptionPane.ERROR_MESSAGE
        );

        return;
    }

    // Layout for multiple platforms
    pnlPlatforms.setLayout(
            new GridLayout(numberOfPlatforms, 1, 5, 5)
    );

    // Create fields for each platform
    for (int i = 0; i < numberOfPlatforms; i++) {

        JPanel platformPanel = new JPanel();

        // Two rows and four columns
        platformPanel.setLayout(
        new java.awt.FlowLayout(
                java.awt.FlowLayout.LEFT,
                5,
                5
        )
);

        JTextField nameField = new JTextField(8);
        JTextField rankField = new JTextField(8);
        JTextField scoreField = new JTextField(8);
        JTextField problemsField = new JTextField(8);

        // Row 1
        platformPanel.add(
                new JLabel("Platform " + (i + 1) + " Name:")
        );

        platformPanel.add(nameField);

        platformPanel.add(
                new JLabel("Rank:")
        );

        platformPanel.add(rankField);

        // Row 2
        platformPanel.add(
                new JLabel("Score:")
        );

        platformPanel.add(scoreField);

        platformPanel.add(
                new JLabel("Problems Solved:")
        );

        platformPanel.add(problemsField);

        // Add platform panel
        pnlPlatforms.add(platformPanel);

        // Store fields
        platformNameFields.add(nameField);
        platformRankFields.add(rankField);
        platformScoreFields.add(scoreField);
        platformProblemsFields.add(problemsField);
    }

    // Refresh panel
    pnlPlatforms.revalidate();
    pnlPlatforms.repaint();
}
